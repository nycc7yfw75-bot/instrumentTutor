// The spotlight's three shades of amber, dark to bright.
var spotShades = [3]color.RGBA{
	lerpCol(tokBG, tokBrand, 0.45),
	lerpCol(tokBG, tokBrand, 0.75),
	tokBrand,
}

var iconImages [iconCount]*ebiten.Image

// iconImage builds an icon's bitmap once: white pixels for tinting, or
// the spotlight's own colours.
func iconImage(id iconID) *ebiten.Image {
	if img := iconImages[id]; img != nil {
		return img
	}
	pix := make([]byte, 4*iconPx*iconPx)
	for y, row := range iconGrids[id] {
		for x, c := range row {
			var col color.RGBA
			switch c {
			case '#':
				col = color.RGBA{255, 255, 255, 255}
			case '1', '2', '3':
				col = spotShades[c-'1']
			default:
				continue
			}
			i := 4 * (y*iconPx + x)
			pix[i], pix[i+1], pix[i+2], pix[i+3] = col.R, col.G, col.B, col.A
		}
	}
	img := ebiten.NewImage(iconPx, iconPx)
	img.WritePixels(pix)
	iconImages[id] = img
	return img
}

// iconSize is the drawn size: 2× the bitmap.
const iconSize = 2 * iconPx

// drawPixelIcon draws an icon at 2×, on whole pixels, tinted col (the
// spotlight keeps its own colours; col's alpha still applies).
func drawPixelIcon(dst *ebiten.Image, id iconID, x, y float64, col color.RGBA) {
	drawPixelIconScaled(dst, id, x, y, 2, col)
}

func drawPixelIconScaled(dst *ebiten.Image, id iconID, x, y float64, scale int, col color.RGBA) {
	op := &ebiten.DrawImageOptions{}
	op.GeoM.Scale(float64(scale), float64(scale))
	op.GeoM.Translate(math.Round(x), math.Round(y))
	op.Filter = ebiten.FilterNearest
	if id == icSpotlight {
		op.ColorScale.ScaleAlpha(float32(col.A) / 255)
	} else {
		op.ColorScale.ScaleWithColor(col)
	}
	dst.DrawImage(iconImage(id), op)
}
